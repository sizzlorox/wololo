import { ADAPTERS, chooseSkillDirs } from '../../adapters/index.js';
import { mcpTools } from '../../core/config.js';
import { splitCommand } from '../../core/exec.js';
import { readText } from '../../core/files.js';
import { templatePath } from '../../core/templates.js';
import { loadAgents, loadSkills } from './sources.js';

/** @typedef {import('../../adapters/types.js').FileOp} FileOp */

/**
 * Everything sync would write, in order. Pure apart from reading canonical sources.
 * @param {import('../../core/types.js').Ctx} ctx
 * @returns {FileOp[]}
 */
export function buildOps(ctx) {
  const { root, config } = ctx;
  const skills = loadSkills(root);
  const agents = loadAgents(root);
  const argv = splitCommand(config.bin);
  const tools = mcpTools(config);
  /** @type {import('../../adapters/types.js').SyncCtx} */
  const sctx = {
    root,
    config,
    skills,
    agents,
    mcp: { command: argv[0], args: [...argv.slice(1), 'mcp', ...(tools ? ['--tools', tools.join(',')] : [])] },
    hook: (harness, event) => `${config.bin} hook ${harness} ${event}`,
  };
  const adapters = config.harnesses.map((id) => ADAPTERS[id]).filter(Boolean);

  /** @type {FileOp[]} */
  const ops = [{ kind: 'block', path: 'AGENTS.md', style: 'md', content: agentsMd(sctx) }];
  for (const dir of chooseSkillDirs(adapters)) {
    for (const s of skills) for (const f of s.files) ops.push({ kind: 'write', path: `${dir}/${s.name}/${f.rel}`, content: f.content });
  }
  for (const a of adapters) ops.push(...a.ops(sctx));
  if (config.ci.provider === 'github') ops.push({ kind: 'write', path: '.github/workflows/wololo.yml', content: ciWorkflow(sctx) });
  return ops;
}

/** @param {import('../../adapters/types.js').SyncCtx} ctx */
function agentsMd(ctx) {
  const tmpl = readText(templatePath('AGENTS.md')) ?? '';
  const skills = ctx.skills.map((s) => `- **${s.name}** — ${s.description} (\`.wololo/skills/${s.name}/SKILL.md\`)`).join('\n');
  const agents = ctx.agents.map((a) => `- **${a.name}** — ${a.description}`).join('\n');
  return tmpl
    .replaceAll('{{bin}}', ctx.config.bin)
    .replaceAll('{{project}}', ctx.config.project)
    .replaceAll('{{skills}}', skills || '- (none yet: `wololo skills new <name>`)')
    .replaceAll('{{agents}}', agents || '- (none)')
    .trim();
}

/** @param {import('../../adapters/types.js').SyncCtx} ctx */
function ciWorkflow(ctx) {
  const setup = ctx.config.ci.setup.map((step) => step.split('\n').map((l, i) => `${i ? '        ' : '      - '}${l}`).join('\n')).join('\n');
  return (readText(templatePath('ci', 'github.yml')) ?? '').replace('{{setup}}', setup || '      # add install steps in wololo.config.json → ci.setup').replaceAll('{{bin}}', ctx.config.bin);
}

const MARK = { md: ['<!-- wololo:begin — generated by `wololo sync`; edit .wololo/ instead -->', '<!-- wololo:end -->'], hash: ['# wololo:begin — generated by `wololo sync`; edit .wololo/ instead', '# wololo:end'] };

/**
 * Insert or replace our managed block, leaving everything else in the file alone.
 * @param {string | undefined} text
 * @param {string} content
 * @param {'md' | 'hash'} style
 */
export function upsertBlock(text, content, style) {
  const [begin, end] = MARK[style];
  const block = `${begin}\n${content}\n${end}`;
  if (!text) return `${block}\n`;
  const b = text.indexOf('wololo:begin');
  const e = text.indexOf('wololo:end', b);
  if (b === -1 || e === -1) return `${text.trimEnd()}\n\n${block}\n`;
  const start = text.lastIndexOf('\n', b) + 1;
  const nl = text.indexOf('\n', e);
  const stop = nl === -1 ? text.length : nl;
  return `${text.slice(0, start)}${block}${text.slice(stop)}`;
}

/**
 * Apply a path's ops on top of its current content.
 * @param {FileOp[]} ops
 * @param {string | undefined} existing
 */
export function render(ops, existing) {
  let text = existing;
  for (const op of ops) {
    if (op.kind === 'write') text = op.content;
    else if (op.kind === 'block') text = upsertBlock(text, op.content, op.style);
    else text = `${JSON.stringify(op.merge(text?.trim() ? JSON.parse(text) : {}), null, 2)}\n`;
  }
  return /** @type {string} */ (text);
}

/** @param {FileOp[]} ops */
export function groupByPath(ops) {
  /** @type {Map<string, FileOp[]>} */
  const map = new Map();
  for (const op of ops) map.set(op.path, [...(map.get(op.path) ?? []), op]);
  return map;
}

