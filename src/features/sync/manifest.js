import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { readJson, writeJson } from '../../core/files.js';
import { MANIFEST_FILE } from '../../core/state.js';

/** @typedef {{ files: Record<string, string> }} Manifest */

/** @param {string} content */
export const hashOf = (content) => createHash('sha256').update(content).digest('hex').slice(0, 16);

/** @param {string} root @returns {Manifest} */
export function readManifest(root) {
  return readJson(join(root, MANIFEST_FILE), { files: {} });
}

/** @param {string} root @param {Record<string, string>} files */
export function writeManifest(root, files) {
  const sorted = Object.fromEntries(Object.entries(files).sort(([a], [b]) => a.localeCompare(b)));
  writeJson(join(root, MANIFEST_FILE), { note: 'Generated by wololo sync. Edit .wololo/ sources, never these copies.', files: sorted });
}

/** Paths wholly generated by sync (never hand-edit, never lint). @param {string} root */
export function generatedPaths(root) {
  return Object.keys(readManifest(root).files);
}
