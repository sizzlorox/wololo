import { existsSync } from 'node:fs';
import { isAbsolute, join, relative } from 'node:path';
import { toPosix } from '../../core/files.js';
import { recordEvent } from '../../core/state.js';
import { readTasks } from '../board/store.js';
import { formatViolation, runCheck } from '../check/engine.js';
import { readQueue } from '../queue/store.js';
import { generatedPaths } from '../sync/manifest.js';
import { computeTrust } from '../trust/compute.js';
import { runVerify } from '../verify/command.js';

/**
 * Pull file paths out of any harness's hook payload (Claude, Copilot, Cursor, Gemini…).
 * @param {unknown} payload
 * @returns {string[]}
 */
export function pathsFrom(payload) {
  /** @type {Set<string>} */
  const out = new Set();
  /** @param {unknown} v @param {number} depth */
  const visit = (v, depth) => {
    if (depth > 6 || !v) return;
    if (typeof v === 'string') {
      if (v.startsWith('{')) {
        try {
          visit(JSON.parse(v), depth + 1);
        } catch {
          // not JSON
        }
      }
      return;
    }
    if (Array.isArray(v)) return v.forEach((x) => visit(x, depth + 1));
    if (typeof v !== 'object') return;
    for (const [k, x] of Object.entries(v)) {
      if (['file_path', 'filePath', 'path', 'notebook_path', 'absolute_path', 'file'].includes(k) && typeof x === 'string') out.add(x);
      else visit(x, depth + 1);
    }
  };
  visit(payload, 0);
  return [...out];
}

/**
 * Format feedback the way each harness feeds it back to the model.
 * Exit 2 + stderr: Claude Code and Gemini CLI show stderr to the agent.
 * @param {string} harness
 * @param {string} event
 * @param {string} message
 * @param {any} payload
 * @returns {import('../../core/types.js').Result}
 */
function feedback(harness, event, message, payload) {
  if (event === 'stop') {
    if (harness === 'claude') {
      if (payload?.stop_hook_active) return { ok: true, summary: '', stdout: '', exitCode: 0 };
      return { ok: true, summary: '', stdout: JSON.stringify({ decision: 'block', reason: message }), exitCode: 0 };
    }
    if (harness === 'cursor') {
      if ((payload?.loop_count ?? 0) >= 3) return { ok: true, summary: '', stdout: '{}', exitCode: 0 };
      return { ok: true, summary: '', stdout: JSON.stringify({ followup_message: message }), exitCode: 0 };
    }
  }
  return { ok: false, summary: '', stdout: '', stderr: message, exitCode: 2 };
}

/** @type {import('../../core/types.js').Command[]} */
export const commands = [
  {
    name: 'hook',
    summary: 'Harness hook entrypoint (post-edit, stop, session-start). Puts rules in front of the agent at the moment they matter.',
    mcp: false,
    args: [
      { name: 'harness', description: 'claude | copilot | cursor | gemini | …', required: true },
      { name: 'event', description: 'post-edit | stop | session-start', required: true },
    ],
    async run(input, ctx) {
      const raw = await ctx.readStdin();
      /** @type {any} */
      let payload = {};
      try {
        payload = raw.trim() ? JSON.parse(raw) : {};
      } catch {
        payload = {};
      }
      const { harness, event } = input;

      if (event === 'session-start') {
        const t = computeTrust(ctx.root);
        const mine = readTasks(ctx.root).filter((x) => x.status !== 'done');
        const open = readQueue(ctx.root).filter((i) => i.status === 'open').length;
        const text = `[wololo] trust L${t.level} (${t.name}). Board: ${mine.length} open task(s), ${open} queued finding(s). Verify with \`${ctx.config.bin} verify\`; merge only when \`${ctx.config.bin} gate\` passes.`;
        return { ok: true, summary: '', stdout: harness === 'claude' ? text : '', exitCode: 0 };
      }

      if (event === 'post-edit') {
        const generated = new Set(generatedPaths(ctx.root));
        const files = pathsFrom(payload)
          .map((p) => toPosix(isAbsolute(p) ? relative(ctx.root, p) : p))
          .filter((p) => !p.startsWith('..') && existsSync(join(ctx.root, p)));
        const touchedGenerated = files.filter((f) => generated.has(f));
        const r = runCheck(ctx, { files: files.filter((f) => !generated.has(f)), record: false });
        /** @type {Record<string, number>} */
        const byRule = {};
        for (const v of r.violations) byRule[v.rule] = (byRule[v.rule] ?? 0) + 1;
        recordEvent(ctx.root, { type: 'hook', ok: r.ok && !touchedGenerated.length, harness, event, byRule });
        const problems = [
          ...touchedGenerated.map((f) => `${f} is generated by wololo sync. Edit the source in .wololo/ and run \`${ctx.config.bin} sync\` instead.`),
          ...r.violations.filter((v) => v.severity === 'error').map(formatViolation),
        ];
        if (!problems.length) return { ok: true, summary: '', stdout: '', exitCode: 0 };
        return feedback(harness, event, `wololo constraints violated by your edit:\n${problems.join('\n')}`, payload);
      }

      if (event === 'stop') {
        const check = runCheck(ctx, { changed: true, record: false });
        const verify = ctx.config.verify.steps.some((s) => s.fast) ? await runVerify(ctx, { fast: true, bail: true }) : { ok: true, results: [] };
        recordEvent(ctx.root, { type: 'hook', ok: check.ok && verify.ok, harness, event });
        if (check.ok && verify.ok) return { ok: true, summary: '', stdout: '', exitCode: 0 };
        const lines = [
          ...check.violations.filter((v) => v.severity === 'error').map(formatViolation),
          ...verify.results.filter((s) => !s.ok).map((s) => `verify step ${s.name} failed:\n${s.output}`),
        ];
        return feedback(harness, event, `Not done yet: the environment says this change is not green.\n${lines.join('\n')}\nFix it (do not weaken the checks), then finish.`, payload);
      }
      return { ok: false, summary: `unknown hook event ${event}`, exitCode: 1 };
    },
  },
];
