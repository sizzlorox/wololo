import { agentFiles, mcpServer } from './types.js';

/**
 * omp hooks are TS modules (`export default (pi) => pi.on(...)`), so wololo ships a thin one that
 * pipes each event to `wololo hook omp <event>` and hands the verdict back to the model.
 * Written as plain JS (valid TS) so it needs no omp type imports.
 * @param {(event: string) => string} hook
 */
const hookModule = (hook) => `// Generated by wololo sync. Edit .wololo/ and run \`wololo sync\` instead.
import { spawnSync } from "node:child_process";

const EDIT_TOOLS = new Set(["edit", "write", "ast_edit", "multi_edit", "notebook"]);
const MAX_STOP_RETRIES = 3;

function wololo(command, payload, cwd) {
  const r = spawnSync(command, { shell: true, cwd, input: JSON.stringify(payload), encoding: "utf8" });
  return r.status === 2 ? (r.stderr || "").trim() : "";
}

export default function (pi) {
  let stopRetries = 0;

  pi.on("tool_result", async (event, ctx) => {
    if (!EDIT_TOOLS.has(event.toolName)) return undefined;
    const problems = wololo(${JSON.stringify(hook('post-edit'))}, { tool_name: event.toolName, tool_input: event.input }, ctx.cwd);
    return problems ? { additionalContext: problems } : undefined;
  });

  pi.on("agent_end", async (_event, ctx) => {
    const problems = wololo(${JSON.stringify(hook('stop'))}, {}, ctx.cwd);
    if (!problems) {
      stopRetries = 0;
      return;
    }
    if (stopRetries >= MAX_STOP_RETRIES) return;
    stopRetries += 1;
    pi.sendMessage({ customType: "wololo", content: problems, display: true }, { triggerTurn: true });
  });
}
`;

import { isSmallWindow } from '../core/config.js';

/** On a small window omp's default tools, LSP and every skill description crowd out the task. */
/**
 * A tool-free run. Not --no-tools: that drops only the built-ins and sends every MCP server's full
 * tool schemas instead (one user's global MCP servers made a 237k-token request). An allowlist with
 * bash folds MCP tools into bash commands, so the request stays small; the prompt says not to use it.
 */
const BARE = ['--tools', 'bash', '--no-skills', '--no-lsp'];
const SLIM = ['--tools', 'read,edit,write,bash,grep,glob', '--no-lsp', '--skills', 'verify,verify-app,tdd'];
/**
 * omp thinks at `high` by default. On a small local model the reasoning alone runs into the output
 * cap: the reply is cut off (stopReason "length"), omp compacts with reason "incomplete" and retries,
 * and it never gets to a tool call. Low thinking leaves room to act.
 */
const SMALL_WINDOW_THINKING = 'low';
const OVERLAY = '.omp/wololo-small-window.yml';

/**
 * omp compacts relative to the window it *believes* the model has (local models are often
 * discovered with a bigger one) and keeps 20k recent tokens by default. Pin both to the real window.
 * @param {number} window
 */
const compaction = (window) => `# Generated by wololo sync for autopilot.contextWindow ${window}. Loaded by headless runs via --config.
compaction:
  enabled: true
  midTurnEnabled: true
  thresholdTokens: ${Math.floor(window * 0.6)}
  reserveTokens: ${Math.floor(window * 0.2)}
  keepRecentTokens: ${Math.floor(window * 0.15)}
`;

/** @type {import('./types.js').Adapter} */
export default {
  id: 'omp',
  label: 'oh-my-pi (omp)',
  binary: 'omp',
  skillDirs: ['.omp/skills', '.claude/skills'],
  stream: ['--mode', 'json'],
  model: (m) => [`--model=${m}`],
  headless: (prompt, { contextWindow, tools = true, thinking } = {}) => {
    const small = isSmallWindow(contextWindow);
    const level = thinking ?? (small ? SMALL_WINDOW_THINKING : undefined);
    return [
      'omp', '-p', prompt, '--yolo',
      ...(!tools ? BARE : small ? SLIM : []),
      ...(level ? ['--thinking', level] : []),
      ...(small ? ['--config', OVERLAY] : []),
    ];
  },
  ops: (ctx) => [
    { kind: 'json', path: '.mcp.json', merge: (o) => ({ ...o, mcpServers: { ...o.mcpServers, wololo: mcpServer(ctx) } }) },
    { kind: 'write', path: '.omp/hooks/post/wololo.ts', content: hookModule((event) => ctx.hook('omp', event)) },
    ...agentFiles('.omp/agents', ctx.agents, (a) => ({ name: a.name, description: a.description })),
    ...(isSmallWindow(ctx.config.autopilot.contextWindow) ? [{ kind: /** @type {const} */ ('write'), path: OVERLAY, content: compaction(/** @type {number} */ (ctx.config.autopilot.contextWindow)) }] : []),
  ],
};
